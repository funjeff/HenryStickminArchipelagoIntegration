def check_if_goal_completed(ctx):
    if ctx.henryslotdata['Goal'] == 0:
        total_ranks = 0
        if ctx.henryslotdata['BtB'] != 0:
            total_ranks = total_ranks + get_num_BtB_ranks_achived(ctx)
        if ctx.henryslotdata['EtP'] != 0:
            total_ranks = total_ranks + get_num_EtP_ranks_achived(ctx)
        if ctx.henryslotdata['StD'] != 0:
            total_ranks = total_ranks + get_num_StD_ranks_achived(ctx)
        if ctx.henryslotdata['ItA'] != 0:
            total_ranks = total_ranks + get_num_ItA_ranks_achived(ctx)
        if ctx.henryslotdata['FtC'] != 0:
            total_ranks = total_ranks + get_num_FtC_ranks_achived(ctx)
        if ctx.henryslotdata['CtM'] != 0:
            total_ranks = total_ranks + get_num_CtM_ranks_achived(ctx)
        
        use_rank_goal = min(get_num_avilable_ranks_from_context(ctx),ctx.henryslotdata['Required_Ranks'])

        if total_ranks >= use_rank_goal:
            return True
        
    elif ctx.henryslotdata['Goal'] == 1 and ctx.henryslotdata['CtM'] != 0:
        return found_CtM_rank(ctx)

    elif ctx.henryslotdata['Goal'] == 2 or (ctx.henryslotdata['Goal'] == 1 and ctx.henryslotdata['CtM'] == 0):
        if ctx.henryslotdata['BtB'] != 0 and not found_BtB_rank(ctx):
            return False
        if ctx.henryslotdata['EtP'] != 0 and not found_EtP_rank(ctx):
            return False
        if ctx.henryslotdata['StD'] != 0 and not found_StD_rank(ctx):
            return False
        if ctx.henryslotdata['ItA'] != 0 and not found_ItA_rank(ctx):
            return False
        if ctx.henryslotdata['FtC'] != 0 and not found_FtC_rank(ctx):
            return False
        if ctx.henryslotdata['CtM'] != 0 and not found_CtM_rank(ctx):
            return False
        return True
    return False

